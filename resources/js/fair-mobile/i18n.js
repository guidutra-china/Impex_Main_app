const NUMBER_LOCALE = { pt_BR: 'pt-BR', en: 'en-US', zh_CN: 'zh-CN' };

/** Normalize an arbitrary locale tag to one we ship (or null). */
export function resolveLocale(raw) {
    if (!raw) return null;
    if (messages[raw]) return raw;
    const lc = String(raw).toLowerCase();
    if (lc.startsWith('pt')) return 'pt_BR';
    if (lc.startsWith('zh')) return 'zh_CN';
    if (lc.startsWith('en')) return 'en';
    return null;
}

/** Best default before the user is known: browser language, then English. */
export function defaultLocale() {
    return resolveLocale(navigator.language) || 'en';
}

/** BCP-47 tag for Intl APIs (number formatting, Intl.DisplayNames). */
export function numberLocale(locale) {
    return NUMBER_LOCALE[locale] || 'en-US';
}

export function t(locale, key, params = {}) {
    const dict = messages[locale] || messages.en;
    let str = dict[key] ?? messages.en[key] ?? key;
    for (const [k, v] of Object.entries(params)) {
        str = str.replace(`:${k}`, v);
    }
    return str;
}
